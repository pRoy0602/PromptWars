/**
 * Returns all distinct states and union territories in India
 */
export function getAllIndianStates(): string[] {
  return INDIAN_STATES;
}

/**
 * Returns all universities belonging to a specific state or UT
 */
export function getUniversitiesForState(state: string): IndianUniversity[] {
  if (!state || state === 'All States') {
    return INDIAN_UNIVERSITIES_DATA;
  }
  return INDIAN_UNIVERSITIES_DATA.filter(
    (u) => u.state.toLowerCase() === state.toLowerCase()
  );
}

/**
 * Search universities by query across name, shortName, city, and state
 */
export function searchIndianUniversities(query: string, stateFilter?: string): IndianUniversity[] {
  const cleanQuery = query.toLowerCase().trim();
  let list = INDIAN_UNIVERSITIES_DATA;

  if (stateFilter && stateFilter !== 'All States') {
    list = list.filter((u) => u.state.toLowerCase() === stateFilter.toLowerCase());
  }

  if (!cleanQuery) {
    return list;
  }

  return list.filter((u) => {
    return (
      u.name.toLowerCase().includes(cleanQuery) ||
      u.shortName.toLowerCase().includes(cleanQuery) ||
      u.city.toLowerCase().includes(cleanQuery) ||
      u.state.toLowerCase().includes(cleanQuery)
    );
  });
}

/**
 * Returns popular featured Indian universities for instant suggestions
 */
export function getPopularIndianUniversities(): IndianUniversity[] {
  return INDIAN_UNIVERSITIES_DATA.filter((u) => u.popular);
}
